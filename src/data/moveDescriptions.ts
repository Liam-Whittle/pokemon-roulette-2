export function getCuratedMoveDescription(
  slug: string,
  level: number,
  power: number,
  category: string,
): string {
  const entry = CURATED_MOVE_DESCRIPTIONS[slug];
  if (entry) {
    return typeof entry === 'function' ? entry(level) : entry;
  }
  if (category === 'status') return 'A status move that does not deal direct damage.';
  const kind = category === 'physical' ? 'physical' : 'special';
  return `Strikes with a ${kind} attack (power ${power}).`;
}
